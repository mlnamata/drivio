export function tagValue(list: readonly string[], key: string): string | undefined {
  const hit = list.find((t) => t.startsWith(`${key}:`));
  return hit?.slice(key.length + 1);
}

export function setTag(list: string[], key: string, value: string | number | undefined) {
  const rest = list.filter((t) => !t.startsWith(`${key}:`));
  return value === undefined || value === "" ? rest : [...rest, `${key}:${value}`];
}

/** Pořadí v uspořádaném číselníku (pro filtry „alespoň“). -1 = vůz hodnotu nemá. */
export function rankIn(list: readonly { value: string }[], tags: readonly string[]) {
  let best = -1;
  list.forEach((o, i) => {
    if (tags.includes(o.value)) best = i;
  });
  return best;
}

export const labelOf = <T extends { value: string; label: string }>(
  list: readonly T[],
  value: string,
) => list.find((i) => i.value === value)?.label ?? value;

